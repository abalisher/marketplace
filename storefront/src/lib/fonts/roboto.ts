import localFont from "next/font/local"

/**
 * Roboto — гарнитура покупательского интерфейса (решение владельца 2026-09-14).
 * Эталон вида — Gemini, но его Google Sans закрыт лицензией; Roboto — ровно тот
 * шрифт, который сам Gemini подставляет вместо Google Sans, и ближайшее к
 * эталону из свободных. Панель продавца остаётся на IBM Plex Sans: у неё другой
 * эталон (идиомы ядра Medusa).
 *
 * Знака тенге (₸) в Roboto нет — он приходит отдельной вырезкой в
 * roboto-tenge.ts, следующей строкой стека `font-sans`.
 *
 * Файл один — переменное начертание (оси wght и wdth), веса 100–900 берутся из
 * него же: это легче четырёх статических файлов (488 КБ против 820 КБ) и
 * закрывает казахскую кириллицу целиком (ә ғ қ ң ө ұ ү һ і — проверено).
 * Шрифт бандлится с витриной (src/fonts), как раньше IBM Plex: сборка и рантайм
 * не зависят от Google Fonts (DECISIONS 2026-07-27).
 *
 * Подключается один раз в корневом layout: класс переменной на <html>,
 * дальше шрифт берётся через Tailwind (`font-sans` → var(--font-roboto)).
 */
export const roboto = localFont({
  src: "../../fonts/Roboto-Variable.ttf",
  weight: "100 900",
  style: "normal",
  variable: "--font-roboto",
  display: "swap",
  // Подстановочное начертание с подогнанными метриками не заводим: next
  // дописывает его ВНУТРЬ var(--font-roboto), и тогда ₸ (которого в Roboto
  // нет) забирает оно, а не наша вырезка следующей строкой стека.
  adjustFontFallback: false,
})
