/// Профиль покупателя для кабинета (T10.6): ФИО, телефон и сохранённые адреса
/// доставки — ровно то, что ассистент подставляет при оформлении (T10.8).
/// Email в профиле нет намеренно: со входом по номеру (T10.7) на учётке лежит
/// служебный `<цифры номера>@phone.invalid`, показывать его покупателю нельзя.
class BuyerProfile {
  const BuyerProfile({this.name, this.phone, this.addresses = const []});

  /// «Имя Фамилия»; `null` — покупатель ещё не назвался.
  final String? name;

  /// Номер телефона учётки; `null` — учётка заведена по email.
  final String? phone;

  /// Сохранённые адреса доставки, одной строкой каждый.
  final List<String> addresses;
}
