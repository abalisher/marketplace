/// Причина, по которой заявка юрлица не ушла или файл не принят. Переводится
/// словарём локали (`Messages.companyApplicationError`).
enum CompanyApplicationError {
  /// Файлов больше, чем разрешает контракт (4).
  tooManyFiles,

  /// Файл тяжелее 3 МБ.
  fileTooLarge,

  /// Тип файла не PDF/JPEG/PNG.
  unsupportedType,

  /// Бэкенд не принял заявку (БИН занят, покупатель уже в компании и т.п.).
  rejected,

  /// Правка пустая: реквизиты не менялись и ни одного файла не приложено
  /// (контракт отвечает 400 — не гоняем заведомо отказной запрос).
  nothingToUpdate,

  /// Бэкенд не принял правку заявки (реквизиты одобренной компании,
  /// исчерпанный общий лимит документов и т.п.).
  updateRejected,

  /// Сеть недоступна.
  network,

  /// Прочий сбой отправки.
  unknown,
}
