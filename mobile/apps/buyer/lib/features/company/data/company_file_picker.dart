import '../domain/company_application_file.dart';

/// Контракт выбора учредительных документов на устройстве. Вынесен из
/// контроллера, чтобы заявку можно было прогонять в тестах без системного
/// диалога; реализация по умолчанию — [PlatformCompanyFilePicker].
abstract interface class CompanyFilePicker {
  /// Открывает системный выбор файлов. Пустой список — покупатель отменил
  /// выбор. Тип содержимого определяется по расширению; нераспознанное
  /// расширение приходит с пустым `mimeType` — такой файл отсеет контроллер.
  Future<List<CompanyApplicationFile>> pickFiles();
}
