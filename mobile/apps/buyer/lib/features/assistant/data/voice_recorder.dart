import '../domain/voice_recording.dart';

/// Граница записи голоса (T10.3): контроллер не знает ни про плагин, ни про
/// контейнер — в тестах подставляется фейк.
///
/// Любая неудача — [VoiceException] с причиной: «молчащая кнопка микрофона»
/// худший из исходов, покупателю всегда говорим, что случилось.
abstract interface class VoiceRecorder {
  /// Открывает микрофон (спросив разрешение) и начинает писать.
  Future<void> start();

  /// Останавливает запись и отдаёт её. `null` — писать было нечего (кнопку
  /// нажали и сразу отпустили): это не ошибка, просто отправлять нечего.
  Future<VoiceRecording?> stop();

  /// Бросает запись и освобождает микрофон.
  Future<void> cancel();

  /// Отпускает ресурсы плагина при уходе с экрана.
  Future<void> dispose();
}
