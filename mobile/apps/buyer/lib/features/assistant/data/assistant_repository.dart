import '../domain/assistant_reply.dart';
import '../domain/assistant_stream_event.dart';
import '../domain/cart_summary.dart';
import '../domain/chat_file.dart';
import '../domain/chat_message.dart';

/// Граница доступа к разговорному ассистенту покупателя. Экран/контроллер не
/// знают про DTO контракта — работают через эту абстракцию (в тестах — фейк).
abstract interface class AssistantRepository {
  /// Отправляет всю историю диалога (последняя реплика — от покупателя) и
  /// удерживаемые токены сессии; возвращает историю с ответом ассистента.
  ///
  /// [files] — вложения ЭТОГО хода (T10.4): фото списка от прораба, скан сметы,
  /// PDF. Относятся они к последней реплике и между ходами не тянутся: файл
  /// нигде не сохраняется и виден модели ровно в том ходе, с которым его
  /// прислали, — иначе каждый следующий ход тащил бы мегабайты картинки заново.
  Future<AssistantReply> send({
    required List<ChatMessage> history,
    String? cartId,
    String? orderId,
    List<ChatFile> files,
  });

  /// Тот же ход, но ответ приходит по мере генерации (T10.1d): поток событий
  /// (текст дельтами → итог хода). Отмена подписки = «Стоп» покупателя: запрос
  /// обрывается, бэкенд гасит ход у модели, уже исполненные инструменты не
  /// откатываются.
  ///
  /// Если поток не открылся, в поток приходит ошибкой
  /// [AssistantStreamUnavailableException] — вызывающий код повторяет ход
  /// обычным [send].
  Stream<AssistantStreamEvent> stream({
    required List<ChatMessage> history,
    String? cartId,
    String? orderId,
    List<ChatFile> files,
  });

  /// Выставляет количества позиций корзины счётчиками «−/+» (T10.15). Хода
  /// модели тут нет: покупатель набирает состав сам, ассистент увидит его на
  /// следующем ходе. Количество АБСОЛЮТНОЕ (сколько должно стать), 0 — убрать
  /// позицию; запрос идемпотентен, поэтому серию нажатий можно схлопывать
  /// дебаунсом. Корзины ещё нет — первое положительное количество её создаёт, и
  /// её id возвращается в [CartSummary.cartId].
  Future<CartSummary> setCartQuantities({
    String? cartId,
    required Map<String, int> quantities,
  });

  /// Читает состав корзины: нужен после хода модели — корзину меняет и сам
  /// ассистент, а полоса корзины обязана показывать правду.
  Future<CartSummary> readCart(String cartId);
}
