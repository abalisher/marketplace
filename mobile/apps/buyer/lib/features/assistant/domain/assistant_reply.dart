import 'chat_message.dart';

/// Результат одного хода ассистента. Бэкенд stateless: возвращает историю,
/// дополненную своим ответом, и токены сессии, которые клиент держит между
/// ходами (корзину/заказ создают инструменты на бэкенде, не клиент).
class AssistantReply {
  const AssistantReply({required this.messages, this.cartId, this.orderId});

  /// Полная история диалога с ответом ассистента (источник истины — бэкенд).
  final List<ChatMessage> messages;

  /// Актуальный id корзины; `null`, пока корзина не создана или уже потрачена.
  final String? cartId;

  /// Id последнего оформленного заказа; `null`, пока заказа нет.
  final String? orderId;

  /// Быстрые ответы следующего шага («Перейти к оформлению», «Я оплатил»):
  /// клиент рисует их чипами под ответом, нажатие отправляет реплику как есть.
}
