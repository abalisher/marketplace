/// Почему выбранный файл не взяли (T10.4c). Причина, а не одно «не получилось»:
/// делать покупателю в каждом случае надо РАЗНОЕ — сжать кадр, убрать лишний
/// файл, сфотографировать таблицу вместо того, чтобы присылать её файлом. Текст
/// выбирает экран — сообщения локализованы.
enum ChatFileFailure {
  /// Формат, который зрительная модель не читает (видео, архив, документ).
  type,

  /// Таблица или документ Word: их разбирает парсер T11.1, а не картинка.
  /// Отказ отдельный от [type] — покупателю есть что сделать прямо сейчас.
  table,

  /// Один файл больше 8 МБ.
  tooLarge,

  /// Файлы хода суммарно больше 12 МБ.
  turnTooLarge,

  /// Файлов больше трёх.
  tooMany,

  /// Нет доступа к камере или галерее. Причина мобильная: в вебе у выбора
  /// файла разрешений нет вовсе, а на телефоне отказ надо объяснить и позвать
  /// в настройки.
  denied,

  /// Файл не прочитался: пустой файл или устройство отдало ошибку.
  failed,
}
