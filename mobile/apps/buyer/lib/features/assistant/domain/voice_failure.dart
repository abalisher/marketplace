/// Почему голосовой ввод не сработал (T10.3). Причина, а не одно «не
/// получилось»: покупателю нужно знать, что делать дальше — разрешить микрофон,
/// проверить устройство или просто набрать текст. Текст выбирает экран —
/// сообщения локализованы.
enum VoiceFailure {
  /// Покупатель (или системная политика) отказал в доступе к микрофону.
  denied,

  /// Микрофона нет, он занят или платформа записи не умеет.
  failed,

  /// Записалось больше, чем принимает бэкенд (8 МБ) — отправлять нечего.
  tooLarge,

  /// Модель ничего не разобрала: тишина или шум. По контракту T10.2 это не
  /// ошибка, а честное «не расслышали» — ручной ввод остаётся на месте.
  empty,
}
