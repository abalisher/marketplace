/// Пределы голосового сообщения (T10.3). Совпадают с серверными
/// (`POST /store/assistant/transcribe`): дольше или тяжелее бэкенд не примет.
/// Держим их на клиенте, чтобы покупатель узнал о пределе во время записи, а не
/// получил отказ после минуты разговора.
class VoiceLimits {
  const VoiceLimits._();

  /// Максимальная длительность записи. По её достижении запись останавливается
  /// САМА и уходит на распознавание — терять сказанное из-за предела нельзя.
  static const Duration maxDuration = Duration(seconds: 60);

  /// Максимальный размер записи (8 МБ). При 16 кГц моно PCM16 минута весит
  /// ~1,9 МБ, так что предел — страховка от неожиданной частоты устройства.
  static const int maxBytes = 8 * 1024 * 1024;
}
