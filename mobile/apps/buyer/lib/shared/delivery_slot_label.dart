import '../l10n/messages.dart';

/// Часы окон приезда — ЗЕРКАЛО домена бэкенда
/// (`backend/src/lib/logistics/delivery-slots.ts`, `DELIVERY_WINDOW_HOURS`).
/// Цифры одинаковы во всех локалях, поэтому живут в коде, а не в словаре;
/// меняются часы на бэкенде — правится и эта таблица.
const deliveryWindowHours = <String, String>{
  'morning': '09:00–13:00',
  'day': '13:00–17:00',
  'evening': '17:00–21:00',
};

/// Подпись слота доставки: «6 сент., 13:00–17:00» (T5.6a). Бэкенд отдаёт слот
/// кодами (дата в календарных сутках Астаны + код окна), фразу собирает клиент
/// на своём языке — так же, как подписывает стадию заказа.
///
/// `null` — слота нет (заказ оформлен до появления слотов) или код окна
/// неизвестен: строку слота на экране тогда не рисуем. Придумывать за бэкенд
/// «время уточним» нельзя — это обещание магазина.
///
/// Дату берём как есть, без `toLocal()`: слот — календарные сутки магазина, а
/// приведение к таймзоне телефона сдвинуло бы «6 сентября» на 5-е западнее
/// Астаны.
String? formatDeliverySlotLabel(DateTime? date, String? window, Messages t) {
  final hours = deliveryWindowHours[window];
  if (date == null || hours == null) return null;
  final month = t.shortMonths[date.month - 1];
  return '${date.day} $month, $hours';
}
