import 'package:core/auth/phone_format.dart';
import 'package:flutter_test/flutter_test.dart';

// Показ номера на экранах: канон бэкенда переводится в человекочитаемый вид,
// всё непохожее на казахстанский номер остаётся как есть.
void main() {
  test('канон превращается в человекочитаемый номер', () {
    expect(formatPhone('+77012345678'), '+7 701 234 56 78');
    // Форматируется только канон бэкенда; междугородняя запись сюда не приходит.
    expect(formatPhone('87012345678'), '87012345678');
  });

  test('неожиданный вид возвращается без изменений', () {
    expect(formatPhone(''), '');
    expect(formatPhone('+7701234'), '+7701234');
    expect(formatPhone('+380501234567'), '+380501234567');
  });
}
