/// Презентационная модель авторизованного СОТРУДНИКА (admin-учётка Medusa):
/// сборщик в `apps/partner`, позже — продавец и кладовщик. Отдельна от
/// `AuthCustomer`: у покупателя своя актор-модель (`/auth/customer/*`),
/// у сотрудника — своя (`/auth/user/*`), и смешивать их в одном состоянии
/// нельзя (на одном устройстве это разные сессии и разные токены).
///
/// Профиля сотрудника в контракте нет (`/admin/users/me` в спеке Store API не
/// публикуется), поэтому единственное, что мы знаем о вошедшем, — email, под
/// которым он вошёл. Он же и есть подпись «кто на смене» на общем складском
/// телефоне. Категория-группа сборщика приходит не отсюда, а из очереди
/// заданий (поле `group`) — сервер подставляет её из учётки.
class StaffUser {
  const StaffUser({required this.email});

  /// Email учётки, под которой вошли (`picker.finishing@stroymarket.kz`).
  final String email;
}
