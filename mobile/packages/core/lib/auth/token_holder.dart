/// Синхронный держатель токена сессии покупателя в памяти. Dio-интерцептор
/// читает [token] на КАЖДОМ запросе синхронно, поэтому персистентное хранилище
/// ([SessionStore], асинхронное) для этого не подходит — holder держит быстрый
/// доступ в памяти, а репозиторий авторизации обновляет обе стороны.
class AuthTokenHolder {
  /// Текущий токен сессии; null — покупатель не авторизован.
  String? token;
}
