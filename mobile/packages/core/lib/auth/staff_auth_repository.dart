import 'staff_user.dart';

/// Авторизация сотрудника (admin-учётка Medusa): вход по email/паролю,
/// восстановление сессии между запусками и выход. Абстракция нужна ровно за
/// тем же, зачем `AuthRepository` покупателю, — экраны и контроллер не знают
/// ни про Dio, ни про сгенерированный клиент, а тесты подставляют фейк.
abstract interface class StaffAuthRepository {
  /// Восстанавливает сессию из хранилища: токен кладётся в держатель, чтобы
  /// интерцептор подписывал запросы. Возвращает null, если сессии нет.
  ///
  /// Токен НЕ проверяется запросом: профиля сотрудника в контракте нет, а
  /// дёргать ради проверки рабочую очередь заданий — лишний круг на старте.
  /// Протухший токен выявится первым же 401 на экране (см. `signOut`).
  Future<StaffUser?> restoreSession();

  /// Вход по email/паролю. Бросает `AuthException` с кодом причины.
  Future<StaffUser> signIn({required String email, required String password});

  /// Выход: токен стирается и из памяти, и из хранилища.
  Future<void> signOut();
}
