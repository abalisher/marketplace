import * as XLSX from "xlsx"

// Шаблон Excel-каталога для компании без 1С: первый лист — пустая таблица с
// заголовками, которые разбор узнаёт (lib/onec/file-feed.ts), второй — как её
// заполнять и пример. Примеры стоят только на втором листе: разбор читает
// первый лист с заголовками, и образцы не попадут в каталог, даже если лист
// с подсказкой оставить в файле.
export const ONEC_TEMPLATE_HEADERS = [
  "Код",
  "Наименование",
  "Бренд",
  "Ед. изм.",
  "Остаток",
  "Цена",
  "Себестоимость",
  "Группа",
]

const EXAMPLE_ROWS: (string | number)[][] = [
  ["00125", "Цемент ПЦ 400-Д20, мешок 50 кг", "Шымкент Цемент", "мешок", 120, 3200, "", "Цемент и смеси"],
  ["00311", "Гипсокартон ГКЛ 12,5 мм 1200×2500", "Knauf", "лист", 450, 2600, "", "Гипсокартон"],
  ["00312", "Гипсокартон ГКЛ 12,5 мм 1200×2500", "Волма", "лист", 300, 2450, "", "Гипсокартон"],
  ["00412", "Арматура А500С 12 мм", "", "т", 3.75, "", 285000, "Металлопрокат"],
]

const GUIDE: string[][] = [
  ["Как заполнить каталог"],
  [""],
  ["1. Заполняйте лист «Каталог»: одна строка — одна позиция. Заголовки не меняйте."],
  ["2. Код — постоянный код позиции в вашем учёте. По нему следующая загрузка находит уже заведённый товар."],
  ["   Код можно не заполнять: площадка присвоит позиции порядковый номер (1, 2, 3…) и закрепит его за ней."],
  ["   Такие позиции связываются по наименованию: переименованная позиция станет новым товаром с новым номером."],
  ["   Бренд — торговая марка. Одинаковые товары разных брендов — разные строки; бренд дописывается к названию на витрине."],
  ["3. Остаток — сколько есть на складе сейчас, в единицах из колонки «Ед. изм.». Дробные числа можно (3,75 т)."],
  ["4. Цена — цена продажи за единицу в тенге. Себестоимость — для справки, ценой продажи она не становится."],
  ["5. Каждый файл — полный каталог: позиции, которых в файле нет, снимаются с витрины (не удаляются)."],
  ["6. Позиция без цены на витрину не попадает, пока цену не задаст продавец."],
  [""],
  ["Пример заполнения:"],
  ONEC_TEMPLATE_HEADERS,
  ...EXAMPLE_ROWS.map((row) => row.map(String)),
]

export const buildOnecFileTemplate = (): Buffer => {
  const workbook = XLSX.utils.book_new()
  const catalog = XLSX.utils.aoa_to_sheet([ONEC_TEMPLATE_HEADERS])
  catalog["!cols"] = [
    { wch: 12 },
    { wch: 48 },
    { wch: 18 },
    { wch: 10 },
    { wch: 10 },
    { wch: 12 },
    { wch: 14 },
    { wch: 22 },
  ]
  XLSX.utils.book_append_sheet(workbook, catalog, "Каталог")
  const guide = XLSX.utils.aoa_to_sheet(GUIDE)
  guide["!cols"] = [{ wch: 110 }]
  XLSX.utils.book_append_sheet(workbook, guide, "Как заполнять")
  return XLSX.write(workbook, { type: "buffer", bookType: "xlsx" }) as Buffer
}
