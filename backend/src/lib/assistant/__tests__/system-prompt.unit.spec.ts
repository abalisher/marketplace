import { buildAssistantSystemPrompt } from "../system-prompt"

// Комплектность набора и пометка запаса (T10.17, фикс находок 3 и 5 Ф-прогона
// T10.16). Тест держит в инструкции ровно то, чего не хватало живому диалогу:
// список сопутствующего ПО КАТЕГОРИЯМ (комплект электрики собрался без розеток)
// и требование называть запас рядом с расчётной цифрой (28 стоек при 25
// расчётных без слова «запас»). Проверяем оба состояния флага юрлиц: секции
// общие для покупателя любого типа и выпасть вместе с юрлицами не должны.
const variants = [
  ["юрлица заморожены", buildAssistantSystemPrompt({ companiesEnabled: false })],
  ["юрлица включены", buildAssistantSystemPrompt({ companiesEnabled: true })],
] as const

describe.each(variants)("системная инструкция (%s)", (_name, prompt) => {
  it("содержит секцию комплектности набора", () => {
    expect(prompt).toContain("<комплектность_набора>")
    expect(prompt).toContain("</комплектность_набора>")
  })

  it.each([
    "РОЗЕТКИ",
    "ВЫКЛЮЧАТЕЛИ",
    "подрозетники",
    "тройники",
    "водорозетки",
    "подвесы",
    "лента на стыки",
    "шпаклёвка",
    "маяки",
  ])("называет сопутствующую позицию «%s»", (item) => {
    expect(prompt).toContain(item)
  })

  it("требует один и тот же диаметр у трубы и фитингов", () => {
    expect(prompt).toContain("ПОД ЭТОТ ЖЕ диаметр")
    expect(prompt).toContain("труба D20 и фитинги D25 вместе не")
  })

  it("требует называть запас рядом с расчётной цифрой", () => {
    expect(prompt).toContain("РЯДОМ С РАСЧЁТНОЙ ЦИФРОЙ")
    expect(prompt).toContain(
      "ни одного количества с запасом без слова\n«запас»"
    )
  })

  it("проверяет комплектность и запас в финальном чеклисте", () => {
    expect(prompt).toContain("<комплектность_набора> пройден ЦЕЛИКОМ")
    expect(prompt).toContain("названо словом «запас» рядом с расчётной")
  })

  it("показывает оба правила примером", () => {
    expect(prompt).toContain("Пример 6")
    expect(prompt).toContain("27 — это запас около 10%")
  })

  // Документы физлицу (решение владельца 2026-09-04, развилка Б; блокер 2
  // Ф-прогона T10.16). В живом диалоге ассистент противоречил себе: «чек или
  // специальные бумажки не понадобятся» и через ход «выдаются розничный счёт и
  // накладная». Правила держим положительными: документы есть ВСЕГДА, чека ККМ
  // нет, счёт — на сумму заказа (Kaspi QR с 2026-11-02 оплачивается после оформления).
  it("запрещает обещать, что документы не понадобятся", () => {
    expect(prompt).toContain("Документы выпускаются ВСЕГДА")
    expect(prompt).toContain(
      "чек или «специальные бумажки» покупателю НЕ понадобятся"
    )
  })

  it("называет фискальный чек тем, чего у платформы нет", () => {
    expect(prompt).toContain("Фискального (кассового) чека ККМ платформа не выдаёт")
    expect(prompt).toContain("счёт и накладную по заказу, каждый с номером и PDF")
  })

  it("объясняет, что счёт — документ на сумму заказа, а не второе требование", () => {
    expect(prompt).toContain("Счёт — документ на сумму заказа")
    expect(prompt).toContain("Это не требование заплатить")
    expect(prompt).toContain("а не «счёт к оплате»")
  })

  it("показывает разговор про чек примером и держит его в чеклисте", () => {
    expect(prompt).toContain("Пример 7 — покупатель-физлицо спрашивает про чек")
    expect(prompt).toContain("Кассового чека у нас нет")
    expect(prompt).toContain("что по заказу будут счёт и накладная")
  })
})
