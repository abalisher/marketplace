export type AssistantPromptOptions = {
  /** Включены ли юрлица (FEATURE_COMPANIES). На MVP — нет, только физлица. */
  companiesEnabled: boolean
  /**
   * Продавец витрины — компания площадки (мультипродавец). null — витрина самой
   * площадки.
   */
  seller?: AssistantSeller | null
  /**
   * Цена доставки канала витрины в тенге — из её shipping option (то, что
   * реально спишется). null — способ доставки не настроен, цену не называем.
   */
  deliveryPrice?: number | null
}

const sellerRole = (seller: AssistantSeller | null | undefined): string =>
  seller
    ? `Ты — консультант компании ${seller.name}${
        seller.bin ? ` (БИН ${seller.bin})` : ""
      }: она продаёт черновые строительные материалы в Астане.`
    : "Ты — консультант интернет-магазина черновых строительных материалов в Астане."

const deliveryPriceRule = (price: number | null | undefined): string =>
  price != null
    ? `- Доставка по Астане стоит ${price} тенге, одинаково для любого заказа. Эту сумму
  называть можно.`
    : `- Стоимость доставки не называй: её покажет счёт после выбора адреса.`

// Собирает системную инструкцию под текущие фича-флаги. Промпт перестал быть
// константой именно поэтому: замороженный домен не должен оставлять в
// инструкции ни следа, иначе модель заговорит о том, чего в продукте нет.
