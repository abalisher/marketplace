// Системная инструкция консультанта покупателя (ру).
//
// Структура — по эталонным промптам агентов-продавцов, опубликованным вендорами
// (Google ADK «Project Pro», OpenAI «NewTelco»/«GreenGather»): секции с явными
// границами, правила приоритета при конфликте, процедура ответа на каждый ход,
// few-shot примеры и финальный чеклист (инструкции в начале И в конце работают
// лучше, чем только в начале). Формулировки ПОЛОЖИТЕЛЬНЫЕ («делай так»), у правил
// названа причина: модель обобщает правило с причиной на новые случаи, а голый
// запрет — заучивает как единичный.
//
// Переписан 2026-08-03 после прогона 10 QA-агентов (docs/qa/2026-08-03-assistant-
// quality-10-agents.md, средний балл 3,57/5). Прежняя версия — ~50 накопленных
// запретов сплошным текстом; отказывала ровно там, где запрет не был написан
// буквально: цены не выдумывала никогда, а сроки, услуги, документы и наличие —
// постоянно (~40 выдуманных утверждений на 10 диалогов).
//
// Секция «КАНОН МАГАЗИНА» — единственный источник правды о том, что магазин умеет
// и чего НЕ умеет. Сверена по коду 2026-08-03: shipping_option «Доставка по
// Астане» (цена — из shipping option канала витрины, см. deliveryPrice); оплата — способы продавца
// (Kaspi QR, перевод на номер Kaspi, «в долг» — lib/payments, с 2026-10-29); постоплата юрлиц
// ОТЛОЖЕНА (docs/modules/scoring.md); счёт+накладная автовыпуском на
// order.placed, внутренний АВР дополнительно для заказа юрлица (subscribers/
// order-invoice.ts); самостоятельная регистрация юрлица POST /store/companies →
// pending → модерация (api/store/companies/route.ts), экран заявки на витрине —
// «Аккаунт → Компания» (storefront /account/company); претензию покупателя
// принимает сам ассистент инструментом open_dispute (модуль reviews, раздел
// «Споры» панели продавца — экрана претензии у покупателя нет ни на одной
// платформе, диалог единственный канал). При изменении этих фактов
// ОБНОВИ канон: расхождение канона с кодом снова превратит консультанта в лгуна.
//
// Секция «КОМПЛЕКТНОСТЬ НАБОРА» добавлена 2026-09-02 по Ф-прогону T10.16
// (docs/qa/2026-09-02-T10.16-focus.md, находки 3 и 5, таск T10.17): правило
// «сначала найди поиском, потом решай» на электрике не срабатывало — комплект
// собрался без розеток, потому что списка сопутствующего ПО КАТЕГОРИЯМ в
// инструкции не было. Там же усилено правило запаса: количество больше
// расчётного без слова «запас» читается покупателем как ошибка расчёта.
// Фрагменты, зависящие от фича-флага FEATURE_COMPANIES (T10.9). Юрлица на MVP
