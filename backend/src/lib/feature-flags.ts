// Фича-флаги платформы: единственный источник правды о том, какие домены входят
// в АКТИВНЫЙ путь. Значение читается из окружения при каждом обращении (а не
// один раз в модульной переменной), чтобы тесты и dev-стенд могли переключать
// флаг без перезапуска процесса.
//
// FEATURE_COMPANIES — юрлица целиком: регистрация компании и её модерация,
// оформление заказа от имени компании, скоринг и кредитный лимит, внутренний
// АВР. На MVP выключен (разворот владельца 2026-08-25, DECISIONS): магазин
// работает ТОЛЬКО с физлицами. Код, таблицы, миграции и данные не удаляются —
// включение флага возвращает функциональность целиком.
//
// Клиенты читают собственные копии флага из своего окружения сборки
// (`NEXT_PUBLIC_FEATURE_COMPANIES` на витрине, `--dart-define=FEATURE_COMPANIES`
// в мобильных, `admin.vite.define` для панели): бандлы собираются заранее и
// про env бэкенда не знают. Значения обязаны совпадать — см. `.env.example`.

const isEnabled = (value: string | undefined): boolean =>
  value === "true" || value === "1"

/** Включены ли юрлица (компании, скоринг, кредитный лимит, внутренний АВР). */
export const isCompaniesEnabled = (): boolean =>
  isEnabled(process.env.FEATURE_COMPANIES)
