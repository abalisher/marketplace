// и метизы). У товара ровно одна категория: по ней ассистент группирует подбор,
// панель фильтрует список, а оплаченный заказ распадается на задания сборки
// (T10.11) — по одному на категорию.
//
// handle — стабильный ключ: имя категории владелец вправе переименовать, а сид,
// панель и классификатор ищут по handle. keywords — слова, по которым товар
// относят к категории при разборе существующего каталога
// (см. classify-product-category.ts); у сидов категория задана явно.

export type CatalogCategoryHandle =
  | "finishing"
  | "electrical"
  | "plumbing"
  | "fasteners"

export type CatalogCategoryDefinition = {
  handle: CatalogCategoryHandle
  name: string
  description: string
  // Слова и фразы, по которым товар относят к категории. Слово совпадает с
  // НАЧАЛОМ слова названия (основа «гвозд» ловит «гвоздь» и «гвозди», но «щит»
  // не ловит «защитный»); фраза из нескольких слов важнее первого слова.
  keywords: string[]
  // Фразы, при которых категория НЕ подходит, даже если слово совпало:
  // «Щиток защитный» — средство защиты, а не электрощит.
  excludes?: string[]
}

