import { defineWidgetConfig } from "@medusajs/admin-sdk"
import { useEffect } from "react"

/*
 * Метка ядровой страницы заказа для слоя оболочки (T4.14c).
 *
 * ЗАЧЕМ. `styles/shell.css` убирает со страницы заказа ядровые действия
 * перехода («Выполнить заказ», «Отметить как отправленный», «Отметить как
 * доставленный»): действия над заказом — только наши, из drawer'а жизненного
 * цикла. Часть селекторов опирается на разметку ядра, которая встречается и на
 * других экранах (контейнер `divide-y p-0` с «…»-меню есть у клиента, товара,
 * склада), поэтому правила нужно ограничить одной страницей.
 *
 * КАК. Виджет ничего не рисует — пока открыта страница заказа, он держит на
 * <html> атрибут `data-sm-page="order"`. Область действия задаёт React: зона
 * `order.details.before` монтируется вместе со страницей и размонтируется при
 * уходе с неё, поэтому атрибут не «залипает» при переходах внутри панели.
 *
 * Как и весь слой оболочки, это ВИД панели, а не права доступа: ядровые
 * эндпоинты остаются доступны, а расхождение статусов, если операцию всё же
 * сделали мимо панели, догоняют подписчики синхронизации (T4.14b).
 */
const OrderPageMode = () => {
  useEffect(() => {
    document.documentElement.dataset.smPage = "order"

    return () => {
      delete document.documentElement.dataset.smPage
    }
  }, [])

  return null
}

export const config = defineWidgetConfig({
  zone: "order.details.before",
})

export default OrderPageMode
