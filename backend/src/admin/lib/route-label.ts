import { PanelLanguage, panelLanguage } from "./locale"

// Подписи пунктов сайдбара и разделов настроек.
//
// Лейбл в `defineRouteConfig({ label })` вычисляется ВНЕ React — хук
// useTranslation там недоступен, поэтому штатный i18n не годится. Из-за этого
// наши разделы раньше оставались английскими и в русской панели соседствовали с
// переведёнными пунктами ядра («Заказы», «Товары», «Настройки») — сайдбар
// выглядел сшитым из двух интерфейсов.
//
// Локаль берём общим детектором панели (lib/locale.ts) — тем же, что у дат:
// cookie `lng`, затем localStorage. Смена языка в профиле применяется к сайдбару
// после перезагрузки страницы (сам дашборд перезагружается при смене языка).

type Label = Record<PanelLanguage, string>

export const routeLabel = (label: Label) => label[panelLanguage]
