import { formatDate, formatDateTime } from "./date"
import { PanelLanguage, panelLanguage } from "./locale"

// Подписи ядра, которых нет в i18n: правило подмены текста (без DOM).
//
// ЗАЧЕМ. Часть надписей дашборд рисует НЕ через i18n, а строкой в коде: на
// карточке платежей это «Total pending», статусы платежа «Pending» /
// «Captured» / «Canceled» и идентификатор провайдера (`pp_kaspi_kaspi`,
// `pp_system_default`, `manual_manual` — ядро просто печатает его с
// `text-transform: capitalize`). Перевести их словарём нельзя: ключа не
// существует. На экране заказа это видит каждый и каждый день — «Total
// pending», «Pp_kaspi_kaspi» назвали мешающими все пять персон Ф-прогонов
// (2026-08-04 и 2026-08-18), а Асель прямо сказала, что цитирует карточку
// покупателю вслух.
//
// КАК. Подмена идёт по ТОЧНОМУ совпадению всего текстового узла: словарь
// маленький и закрытый, поэтому правило либо срабатывает на той самой надписи,
// либо не срабатывает вовсе. Если ядро изменит строку — ничего не подменится
// (вернётся английский), но подписать чужое место русским словом правило не
// может. Единственное исключение из словаря — дата ядра: у неё узнаваемая
// форма целиком («02 Sep, 2026, 14:02:49»), а значений бесконечно много.
// Применяет правило `shell-mode.ts`.
//
// ЧТО ЭТО НЕ ЕСТЬ. Не перевод панели: перевод живёт в `i18n/json/*` и
// подставляется ядром. Сюда попадает только то, чего в i18n ядра нет.

const CORE_LABELS: Record<string, string> = {
  // Карточка платежей на странице заказа.
  "Total pending": "Ожидает оплаты",
  // Ссылка «добавить адрес» в карточке покупателя.
  Add: "Добавить",
  Pending: "Ожидает",
  Captured: "Оплачен",
  Canceled: "Отменён",
  // Идентификаторы провайдеров: ядро печатает их как есть.
  pp_kaspi_kaspi: "Kaspi QR",
  // Системный провайдер ядра — оплата, которую отмечают руками (демо-заказы,
  // оплата на месте), а не какой-то «default».
  pp_system_default: "Оплата вручную",
  // Ядровый провайдер доставки: возим сами, сторонней службы в MVP нет.
  manual_manual: "Своя доставка",
}

// Дата ядра «02 Sep, 2026, 14:02:49» (строка платежа, журнал активности): её
// дашборд печатает своим форматтером с английскими месяцами независимо от
// языка панели, ключа в i18n нет. Рядом с нашими «2 сент. 2026 г.» это читалось
// как чужой экран (Ф-прогоны Данияра и Тимура 2026-08-18). Правило узнаёт
// ровно эту форму и пересчитывает дату общим форматтером панели (`date.ts`) —
// другого источника дат в панели нет.
const CORE_DATE =
  /^(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec), (\d{4})(?:,\s+(\d{1,2}):(\d{2})(?::(\d{2}))?)?$/

const MONTHS = [
  "Jan",
  "Feb",
  "Mar",
  "Apr",
  "May",
  "Jun",
  "Jul",
  "Aug",
  "Sep",
  "Oct",
  "Nov",
  "Dec",
]

const coreDate = (text: string): string | null => {
  const match = CORE_DATE.exec(text)

  if (!match) {
    return null
  }

  const [, day, month, year, hours, minutes] = match
  const date = new Date(
    Number(year),
    MONTHS.indexOf(month),
    Number(day),
    Number(hours ?? 0),
    Number(minutes ?? 0)
  )

  // Секунды не переносим: в строке платежа они не работают, а формат дат в
  // панели один — «день месяц год, часы:минуты».
  return hours
    ? formatDateTime(date.toISOString())
    : formatDate(date.toISOString())
}

// Строки-поля ядра, которые продавцу стройматериалов не нужны: таможенные коды
// в карточке товара. «MID код», «HS код» — техмусор в Ф-прогонах Данияра и
// Жанны (2026-08-18): «таможенные поля, продавцу стройматериалов не нужны».
// Ключи — обе локали панели: подпись берётся из i18n ядра и зависит от языка.
const NOISE_ROW_TITLES = new Set(["MID код", "HS код", "Mid code", "HS code"])

/**
 * Наша подпись вместо ядровой или `null`, если строка не наша.
 *
 * Словарь русский, поэтому в английской панели он не применяется: там ядровая
 * надпись и так на своём языке. Дата пересчитывается всегда — она приходит
 * английской независимо от языка панели, а формат берётся из локали.
 */
export const coreLabel = (
  text: string,
  language: PanelLanguage = panelLanguage
): string | null => {
  const key = text.trim()

  if (!key) {
    return null
  }

  const label =
    (language === "ru" ? CORE_LABELS[key] : undefined) ?? coreDate(key)

  return label && label !== text ? label : null
}

/**
 * Строка-поле с такой подписью убирается со страницы целиком.
 */
export const isNoiseRowTitle = (text: string): boolean =>
  NOISE_ROW_TITLES.has(text.trim())
