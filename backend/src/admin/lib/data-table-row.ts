// Строка, пришедшая в `onRowClick` ядрового `useDataTable`.
//
// По документации ядра колбэк получает ДАННЫЕ строки, но в установленной
// версии DataTable отдаёт обёртку TanStack (`{ original }`). Читаем оба
// варианта — версия ядра может это поправить, и тогда придёт сама строка.
//
// Класс дефекта ловился дважды и оба раза стоил рабочего экрана:
// - T4.2b: клик по строке очереди заказов молча ничего не делал (`row.order`
//   был undefined), и очередь оставалась тупиком — блокер 1 Мадины;
// - T4.11a: клик по претензии РОНЯЛ экран «Споры» — в drawer уходила обёртка,
//   `DISPUTE_STATUS_META[undefined].color` рушил рендер (Ф-прогон 2026-08-18,
//   блокер Асель и Тимура), а клик по строке реестра документов молчал.
//
// Поэтому распаковка живёт в ОДНОМ месте, а не копией в каждом экране: там,
// где `getRowId` возвращает id сущности, обёртка маскируется под строку
// (`row.id` совпадает) и дефект не виден до первого обращения к другому полю.
export const dataTableRow = <T>(row: T): T =>
  (row as { original?: T }).original ?? row
