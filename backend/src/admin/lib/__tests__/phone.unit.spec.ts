import { formatPhone, phoneSearchTerm } from "../phone"

// Номер телефона в панели показывается человеку, а в базе лежит каноном
// (+77012345678). Оба правила — в одном файле, потому что второе существует
// ровно из-за первого: продавец копирует номер С ЭКРАНА в поиск.

describe("formatPhone", () => {
  it("разбивает канон на группы", () => {
    expect(formatPhone("+77012345678")).toBe("+7 701 234 56 78")
  })

  it("оставляет как есть всё, что не казахстанский канон", () => {
    expect(formatPhone("+12025550143")).toBe("+12025550143")
    expect(formatPhone("не номер")).toBe("не номер")
  })
})

describe("phoneSearchTerm", () => {
  it("сжимает номер с экрана в цифры канона", () => {
    // Ровно тот случай, ради которого правило и заведено: продавец копирует
    // номер из колонки «Телефон» и вставляет в поиск.
    expect(phoneSearchTerm("+7 701 234 56 78")).toBe("77012345678")
    expect(phoneSearchTerm("+7 (701) 234-56-78")).toBe("77012345678")
  })

  it("междугороднюю запись через 8 приводит к 7", () => {
    expect(phoneSearchTerm("8 701 234 56 78")).toBe("77012345678")
  })

  it("кусок номера ищет куском канона", () => {
    expect(phoneSearchTerm("701 234")).toBe("701234")
  })

  it("имя и фамилию не трогает", () => {
    expect(phoneSearchTerm("Бауыржан")).toBe("Бауыржан")
    expect(phoneSearchTerm("  Сатыбалдиев ")).toBe("Сатыбалдиев")
    // Восьмёрка в середине слова — не номер.
    expect(phoneSearchTerm("ГАЗ-3307")).toBe("ГАЗ-3307")
  })
})
