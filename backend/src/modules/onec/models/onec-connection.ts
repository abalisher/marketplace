import { model } from "@medusajs/framework/utils"

// Откуда приходит каталог компании: HTTP-сервис её 1С (забирается по
// расписанию) или Excel-файл, который продавец или площадка загружают с экрана
// «1С и Excel». Дальше путь один — разбор, план и применение (lib/onec/sync.ts).
export const ONEC_SOURCES = ["http", "file"] as const
export type OnecSource = (typeof ONEC_SOURCES)[number]

// Подключение компании к её базе 1С. У каждой компании площадки своя база (своя
// номенклатура, цены и остатки), и каталог компании на площадке повторяет её:
// товары, цены и остатки приходят из 1С, а не правятся руками.
//
// tenant_id — опазная колонка (модуль tenant не импортируем), как
// sales_channel_id у самой компании. Одна компания — одно подключение.
//
// Пароль хранится ТОЛЬКО зашифрованным (lib/onec/secret.ts): открытым текстом в
// базе ему не место, а наружу (в API и журнал) он не отдаётся вовсе — экран
// знает лишь, что пароль задан.
const OnecConnection = model.define("onec_connection", {
  id: model.id({ prefix: "onec" }).primaryKey(),
  tenant_id: model.text().unique(),
  source: model.enum([...ONEC_SOURCES]).default("http"),
  // Полный адрес HTTP-сервиса выгрузки номенклатуры, например
  // https://1cfresh.kz/a/ea60/107068/hs/items/getxtsitems. У файлового
  // подключения адреса, логина и пароля нет.
  base_url: model.text().nullable(),
  // Необязательный второй сервис — остатки (и цены) по позициям, например
  // …/hs/items/getitems. Номенклатура и остатки в 1С часто выгружаются разными
  // сервисами; синхронизация сводит их по коду позиции. Пустой ответ этого
  // сервиса остатков не обнуляет.
  stock_url: model.text().nullable(),
  login: model.text().nullable(),
  password_cipher: model.text().nullable(),
  // Выключенное подключение по расписанию не синхронизируется; ручной запуск с
  // экрана работает всегда — так подключение проверяют до включения.
  enabled: model.boolean().default(false),
  // Как часто синхронизировать по расписанию (минуты).
  interval_minutes: model.number().default(30),
  // Каталог компании = только товары из 1С: после удачной синхронизации товары
  // канала, которых нет в 1С (общий демо-каталог площадки), из канала убираются.
  // Сами товары не удаляются — они остаются у площадки и других компаний.
  exclusive_catalog: model.boolean().default(true),
  // Склад компании, на который ложатся остатки из 1С. Пусто — первый склад
  // канала продаж компании.
  stock_location_id: model.text().nullable(),
})

export default OnecConnection
