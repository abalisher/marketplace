import { maskPhone, normalizePhone } from "../normalize-phone"

// Канон номера — единственный ключ учётки покупателя, поэтому проверяем все
// формы записи, которые человек набирает руками.
describe("normalizePhone", () => {
  it("приводит к канону +7XXXXXXXXXX любые формы записи", () => {
    const expected = "+77012345678"
    for (const input of [
      "+77012345678",
      "+7 701 234 56 78",
      "+7 (701) 234-56-78",
      "87012345678",
      "8 701 234 56 78",
      "7012345678",
      "  +7-701-234-56-78  ",
    ]) {
      expect(normalizePhone(input)).toEqual(expected)
    }
  })

  it("отклоняет всё, что не мобильный номер Казахстана", () => {
    for (const input of [
      "",
      "   ",
      "701234567", // короче на цифру
      "770123456789", // длиннее
      "+79261234567", // российский мобильный
      "+77172123456", // городской Астаны
      "не номер",
    ]) {
      expect(normalizePhone(input)).toBeNull()
    }
  })
})

describe("maskPhone", () => {
  it("оставляет код оператора и две последние цифры", () => {
    expect(maskPhone("+77012345678")).toEqual("+7 701 XXX XX 78")
  })

  it("возвращает вход как есть, если это не канон", () => {
    expect(maskPhone("8701")).toEqual("8701")
  })
})
