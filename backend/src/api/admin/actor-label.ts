// Подпись автора действия на экранах панели: журнал правок цен, кто закрыл
// задание сборки. Показываем имя учётки, а если имени нет — логин из почты без
// домена: «admin@example.com» → «admin».
//
// ЗАЧЕМ. Кладовщик читает графу «Кто» как «кто из наших», а видел там почту
// владельческой учётки (Ф-прогон Данияра 2026-09-02, «мешает» №3). Почта в
// журнале — технический адрес: домен не добавляет ничего, а строку удлиняет.
// Настоящее имя учётка получает в «Настройки → Профиль» (или из скрипта
// создания: create-seller-user.ts ставит «Продавец») — тогда в журнале стоит
// оно, и это правило не срабатывает.
//
// Правило применяется на ЧТЕНИИ, а не при записи: в журнале лежит снимок имени
// на момент правки (модель PriceChange), и он остаётся честным — почтой
// подписаны и уже записанные строки.
export const actorLabel = (raw?: string | null): string | null => {
  const value = raw?.trim()
  if (!value) {
    return null
  }
  const at = value.lastIndexOf("@")
  // Почта без локальной части («@example.com») — не режем: пустая подпись
  // хуже адреса.
  if (at <= 0) {
    return value
  }
  const local = value.slice(0, at).trim()
  return local || value
}
