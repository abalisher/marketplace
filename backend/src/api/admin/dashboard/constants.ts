import { OrderStatusValue } from "../../../modules/order-lifecycle/models/statuses"

// Статусы, при которых заказ ещё в работе магазина. Доставленные, закрытые,
// отменённые и возвращённые в сводку не попадают — по ним делать нечего.
//
// «В доставке» добавлен в T4.12: именно этот статус и был слепым пятном —
// «три заказа шестой день висят „В доставке“, и увидеть это в панели нельзя»
// (Ф-прогон 2026-08-18). Заказ в пути магазин ещё не отдал: он в сводке, в
// очереди дашборда, в деньгах в работе и в счётчике просрочки — одним срезом,
// чтобы числа плитки и экрана не расходились (урок T10.14e).
export const OPEN_ORDER_STATUSES: OrderStatusValue[] = [
  "new",
  "confirmed",
  "assembling",
  "partially_assembled",
  "assembled",
  "in_delivery",
]

// Сколько строк показываем в панелях дашборда (полные списки — свои экраны).
export const QUEUE_PREVIEW_LIMIT = 5
export const STOCK_PREVIEW_LIMIT = 4
export const RECEIPTS_PREVIEW_LIMIT = 3

// Порог «низкого остатка» в единицах хранения. Временный единый порог до
// наполнения боевого каталога (T7.2), где пороги задаются по позициям. Порог
// один на плитку дашборда и на чипы экрана «Цены и остатки»: они считают один
// и тот же срез (см. loadStock в summary.ts).
const DEFAULT_LOW_STOCK_THRESHOLD = 10

export function lowStockThreshold(): number {
  const raw = Number(process.env.DASHBOARD_LOW_STOCK_THRESHOLD)
  return Number.isFinite(raw) && raw >= 0 ? raw : DEFAULT_LOW_STOCK_THRESHOLD
}

// Валюта магазина. Медуза допускает заказ в любой валюте региона, но магазин
// один и торгует в тенге — денежные итоги дашборда складываются только по ней.
// Заказы в другой валюте (остались на стенде от ранних прогонов) в суммы НЕ
// попадают, но считаются отдельным числом: иначе сводка молча врала бы.
export const SHOP_CURRENCY = "kzt"

// Часовой пояс магазина: «выручка за день» — это его день, а не день UTC-сервера.
// В Астане UTC+5, к полуночи по серверу разница даёт минус пять часов продаж.
export function shopTimeZone(): string {
  return process.env.SHOP_TIME_ZONE?.trim() || "Asia/Almaty"
}

// Сколько дней покрывает «выручка за неделю» — скользящее окно, включая сегодня.
export const REVENUE_WEEK_DAYS = 7

// Потолок выборки заказов для денежной сводки и отчёта по стадиям. Магазин
