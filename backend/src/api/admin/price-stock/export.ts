// Выгрузка среза экрана «Цены и остатки» (T10.14c): та же таблица, что на
// экране, только файлом. Продавец правит её в Excel и загружает обратно —
// поэтому колонки выгрузки и колонки, которые понимает импорт, это один список.
//
// Технических id в файле нет: ключ строки — АРТИКУЛ. Позиция без артикула
// обратно не загрузится, и файл говорит об этом прямо в клетке.

import { PriceStockRow, priceStockRowTitle } from "./rows"

// Заголовок выгрузки. «Свободно» — только для чтения (лежит минус резерв):
// импорт эту колонку не понимает, продавец правит «Остаток».
export const PRICE_STOCK_EXPORT_HEADER = [
  "Артикул",
  "Товар",
  "Категория",
  "Единица",
  "Цена, ₸",
  "Остаток",
  "Свободно",
  "Склад",
]

// Что стоит в клетке артикула у позиции без артикула: пустая клетка выглядела
// бы как «сотрите и впишите», а вписывать некуда — артикул заводят в карточке.
export const PRICE_STOCK_EXPORT_NO_SKU = "нет артикула"

// Пустая цена остаётся пустой клеткой, а не нулём: «цена не назначена» и «цена
// ноль» — разные вещи, и импорт пустую клетку не трогает.
export const buildExportTable = (
  rows: PriceStockRow[]
): (string | number | null)[][] => [
  PRICE_STOCK_EXPORT_HEADER,
  ...rows.map((row) => [
    row.sku ?? PRICE_STOCK_EXPORT_NO_SKU,
    priceStockRowTitle(row),
    row.category_name ?? "",
    row.unit ?? "",
    row.price ?? "",
    row.stocked,
    row.available,
    row.location_name ?? "",
  ]),
]

// Имя файла — латиницей и с датой: файл живёт в «Загрузках» продавца рядом с
// десятком таких же, а кириллица в заголовке ответа кодируется по-разному в
// разных браузерах.
export const priceStockFileName = (date: Date): string =>
  `price-stock-${date.toISOString().slice(0, 10)}.csv`
